  // 2. Relative time mapping
  const TIME_REGEX = /^(\d+)\s*(m|h|d|w|mo|y)$/;
  const TIME_UNITS = {
    m: ' хв',
    h: ' год',
    d: ' дн',
    w: ' тиж',
    mo: ' міс',
    y: ' р'
  };

  /**
   * Universal translation lookup with suffix and timestamp handling
   */
  function getTranslation(str) {
    if (!str) return null;
    const trimmed = str.trim();
    if (!trimmed) return null;

    if (trimmed.toLowerCase() === 'now') return 'зараз';
    if (trimmed.toLowerCase() === 'just now') return 'щойно';

    if (Object.prototype.hasOwnProperty.call(TRANSLATIONS, trimmed)) {
      return TRANSLATIONS[trimmed];
    }

    const tm = trimmed.match(TIME_REGEX);
    if (tm && TIME_UNITS[tm[2]]) {
      return tm[1] + TIME_UNITS[tm[2]];
    }

    if (trimmed.endsWith('...') && Object.prototype.hasOwnProperty.call(TRANSLATIONS, trimmed.slice(0, -3))) {
      return TRANSLATIONS[trimmed.slice(0, -3)] + '...';
    }
    if (trimmed.endsWith('…') && Object.prototype.hasOwnProperty.call(TRANSLATIONS, trimmed.slice(0, -1))) {
      return TRANSLATIONS[trimmed.slice(0, -1)] + '…';
    }
    if (trimmed.endsWith(':') && Object.prototype.hasOwnProperty.call(TRANSLATIONS, trimmed.slice(0, -1))) {
      return TRANSLATIONS[trimmed.slice(0, -1)] + ':';
    }

    return null;
  }

  // 3. Selectors
  const CODE_CONTAINERS = 'pre, code, .monaco-editor, .xterm, .notranslate, [data-notranslate], .google-symbols, .material-symbols-outlined, .material-symbols, .material-icons, .codicon';
  const TRANSLATABLE_ATTRS = ['placeholder', 'title', 'aria-label', 'data-placeholder'];

  const IGNORE_TEXT_TAGS = [
    'pre',
    'code',
    'textarea',
    'input',
    'script',
    'style',
    'noscript',
    'svg',
    'kbd',
    'samp',
    '.monaco-editor',
    '.xterm',
    '.notranslate',
    '[data-notranslate]',
    '.google-symbols',
    '.material-symbols-outlined',
    '.material-symbols',
    '.material-icons',
    '.codicon'
  ].join(', ');

  /**
   * Checks whether a text node container should be ignored.
   * Allows placeholder overlays even inside editor containers.
   */
  function isTextIgnored(el) {
    if (!el || el.nodeType !== Node.ELEMENT_NODE) return false;
    // Always translate placeholder overlays
    if (el.closest('.placeholder, [class*="placeholder"], [data-placeholder]')) {
      return false;
    }
    if (el.closest(IGNORE_TEXT_TAGS)) return true;
    // Do not translate user typing inside contenteditable
    if (el.closest('[contenteditable="true"]')) return true;
    return false;
  }

  /**
   * Translates attributes on an element (placeholders, tooltips, aria-labels).
   */
  function translateAttributes(el) {
    if (!el || el.nodeType !== Node.ELEMENT_NODE) return;
    if (el.closest(CODE_CONTAINERS)) return;

    for (let i = 0; i < TRANSLATABLE_ATTRS.length; i++) {
      const attr = TRANSLATABLE_ATTRS[i];
      const val = el.getAttribute(attr);
      if (val) {
        const translated = getTranslation(val);
        if (translated && translated !== val) {
          el.setAttribute(attr, translated);
        }
      }
    }
  }

  /**
   * Translates a single text node preserving leading/trailing whitespace.
   */
  function translateTextNode(node) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    if (node._i18n_uk && node._i18n_lastValue === node.nodeValue) return;

    const raw = node.nodeValue;
    if (!raw || !raw.trim()) return;

    const parent = node.parentElement;
    if (!parent || isTextIgnored(parent)) return;

    const translated = getTranslation(raw);
    if (translated && translated !== raw.trim()) {
      const lead = raw.match(/^\s*/)[0];
      const trail = raw.match(/\s*$/)[0];
      const newText = lead + translated + trail;
      node.nodeValue = newText;
      node._i18n_uk = true;
      node._i18n_lastValue = newText;
    }
  }

  /**
   * Traverses a DOM subtree to translate text nodes and attributes.
   */
  function walkAndTranslate(root) {
    if (!root) return;

    if (root.nodeType === Node.ELEMENT_NODE) {
      translateAttributes(root);
    } else if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }

    const walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
      {
        acceptNode: function(node) {
          if (node.nodeType === Node.ELEMENT_NODE) {
            if (node.closest(CODE_CONTAINERS)) {
              return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
          }
          if (node.nodeType === Node.TEXT_NODE) {
            const p = node.parentElement;
            if (!p || isTextIgnored(p)) {
              return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
          }
          return NodeFilter.FILTER_SKIP;
        }
      }
    );

    let curr = walker.nextNode();
    while (curr) {
      if (curr.nodeType === Node.ELEMENT_NODE) {
        translateAttributes(curr);
      } else if (curr.nodeType === Node.TEXT_NODE) {
        translateTextNode(curr);
      }
      curr = walker.nextNode();
    }
  }

  // 4. Batched MutationObserver
  let pendingMutations = [];
  let rafId = null;

  function processPendingMutations() {
    rafId = null;
    const targets = pendingMutations;
    pendingMutations = [];

    for (let i = 0; i < targets.length; i++) {
      const target = targets[i];
      if (target && target.isConnected) {
        walkAndTranslate(target);
      }
    }
  }

  function queueMutation(target) {
    if (!target) return;
    pendingMutations.push(target);
    if (!rafId) {
      rafId = requestAnimationFrame(processPendingMutations);
    }
  }

  const observer = new MutationObserver(function(mutations) {
    for (let i = 0; i < mutations.length; i++) {
      const m = mutations[i];
      if (m.type === 'childList') {
        for (let j = 0; j < m.addedNodes.length; j++) {
          queueMutation(m.addedNodes[j]);
        }
      } else if (m.type === 'characterData') {
        const target = m.target;
        if (target && !target._i18n_uk) {
          translateTextNode(target);
        }
      } else if (m.type === 'attributes') {
        if (TRANSLATABLE_ATTRS.includes(m.attributeName)) {
          translateAttributes(m.target);
        }
      }
    }
  });

  function startObserver() {
    const target = document.body || document.documentElement;
    if (target) {
      walkAndTranslate(target);
      observer.observe(target, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: TRANSLATABLE_ATTRS
      });
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', startObserver);
  } else {
    startObserver();
  }

  window.addEventListener('load', function() {
    setTimeout(function() {
      const root = document.body || document.documentElement;
      if (root) walkAndTranslate(root);
    }, 400);
  });
