    target_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "uk_translations.json")
    existing = {}
    if os.path.exists(target_path):
        try:
            with open(target_path, "r", encoding="utf-8") as f:
                existing = json.load(f)
            print(f"[Merge] Loaded {len(existing)} existing translations from {target_path}")
        except Exception as e:
            print(f"[Warning] Failed to load existing translations ({e}). Starting fresh.")

    # Safe merge: start with existing, merge TRANSLATIONS, never lose keys
    merged = dict(existing)
    merged.update(TRANSLATIONS)
    new_keys_count = len(merged) - len(existing)

    with open(target_path, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False, indent=2)

    print(f"[Success] Saved {len(merged)} Ukrainian translations to {target_path} (+{new_keys_count} new)")

